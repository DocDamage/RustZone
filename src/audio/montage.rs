use std::path::{Path, PathBuf};
use super::buffer::AudioBuffer;
use super::renderer::{render_to_wav, ExportBitDepth, RenderOptions, RenderSource};
use super::resample::SincResampler;

/// Individual track within an Album Mastering Montage
#[derive(Clone, Debug)]
pub struct MontageTrack {
    pub id: usize,
    pub path: PathBuf,
    pub title: String,
    pub artist: String,
    pub duration_seconds: f64,
    pub sample_rate: u32,
    pub integrated_lufs: f32,
    pub true_peak_dbtp: f32,
    pub gain_offset_db: f32,
    pub pause_gap_seconds: f64, // Red Book CD pause gap (default 2.0s)
    pub is_active: bool,
}

impl MontageTrack {
    pub fn new(id: usize, path: PathBuf, title: String, duration_seconds: f64, sample_rate: u32) -> Self {
        Self {
            id,
            path,
            title,
            artist: "Various Artists".to_string(),
            duration_seconds,
            sample_rate,
            integrated_lufs: -18.0,
            true_peak_dbtp: -1.0,
            gain_offset_db: 0.0,
            pause_gap_seconds: 2.0,
            is_active: true,
        }
    }
}

/// Complete Multi-Track Album Montage Sequence
#[derive(Clone, Debug)]
pub struct AlbumMontage {
    pub album_title: String,
    pub album_artist: String,
    pub tracks: Vec<MontageTrack>,
    pub target_album_lufs: f32,
    next_track_id: usize,
}

impl Default for AlbumMontage {
    fn default() -> Self {
        Self::new("Mastered Album", "Mastering Studio")
    }
}

impl AlbumMontage {
    pub fn new(album_title: &str, album_artist: &str) -> Self {
        Self {
            album_title: album_title.to_string(),
            album_artist: album_artist.to_string(),
            tracks: Vec::new(),
            target_album_lufs: -14.0,
            next_track_id: 1,
        }
    }

    /// Add a track to the album sequence
    pub fn add_track(&mut self, path: PathBuf, duration_sec: f64, sample_rate: u32) -> usize {
        let title = path
            .file_stem()
            .unwrap_or_default()
            .to_string_lossy()
            .to_string();
        let track = MontageTrack::new(self.next_track_id, path, title, duration_sec, sample_rate);
        let id = self.next_track_id;
        self.next_track_id += 1;
        self.tracks.push(track);
        id
    }

    /// Remove a track by ID
    pub fn remove_track(&mut self, id: usize) {
        self.tracks.retain(|t| t.id != id);
    }

    /// Re-order tracks (move track from source index to destination index)
    pub fn move_track(&mut self, from_idx: usize, to_idx: usize) {
        if from_idx < self.tracks.len() && to_idx < self.tracks.len() && from_idx != to_idx {
            let item = self.tracks.remove(from_idx);
            self.tracks.insert(to_idx, item);
        }
    }

    /// Total runtime of the album including configured pause gaps
    pub fn total_duration_seconds(&self) -> f64 {
        let mut total = 0.0;
        for (i, t) in self.tracks.iter().filter(|t| t.is_active).enumerate() {
            total += t.duration_seconds;
            if i > 0 {
                total += t.pause_gap_seconds;
            }
        }
        total
    }

    /// Automatically balance perceived loudness across all tracks on the album to hit `target_album_lufs`
    pub fn auto_balance_album_lufs(&mut self) {
        let target = self.target_album_lufs;
        for t in &mut self.tracks {
            if t.integrated_lufs > -60.0 {
                let delta = target - t.integrated_lufs;
                // Clamp delta offset to prevent excessive clipping (+6 dB max boost, -12 dB cut)
                t.gain_offset_db = delta.clamp(-12.0, 6.0);
            }
        }
    }

    /// Generate Red Book CD compliant CUE sheet for plant replication & DDP export
    pub fn generate_cue_sheet(&self, audio_filename: &str) -> String {
        let mut cue = String::new();
        cue.push_str("REM Generated by Mastering Studio\n");
        cue.push_str(&format!("PERFORMER \"{}\"\n", self.album_artist));
        cue.push_str(&format!("TITLE \"{}\"\n", self.album_title));
        cue.push_str(&format!("FILE \"{}\" WAVE\n", audio_filename));

        let mut cumulative_sec = 0.0f64;

        for (idx, track) in self.tracks.iter().filter(|t| t.is_active).enumerate() {
            let track_num = idx + 1;
            cue.push_str(&format!("  TRACK {:02} AUDIO\n", track_num));
            cue.push_str(&format!("    TITLE \"{}\"\n", track.title));
            cue.push_str(&format!("    PERFORMER \"{}\"\n", track.artist));

            // If pause gap exists and not the very first track, insert INDEX 00 (pregap)
            if idx > 0 && track.pause_gap_seconds > 0.01 {
                let pregap_time = Self::seconds_to_cue_time(cumulative_sec);
                cue.push_str(&format!("    INDEX 00 {}\n", pregap_time));
                cumulative_sec += track.pause_gap_seconds;
            }

            let start_time = Self::seconds_to_cue_time(cumulative_sec);
            cue.push_str(&format!("    INDEX 01 {}\n", start_time));
            cumulative_sec += track.duration_seconds;
        }

        cue
    }

    /// Helper converting seconds to CUE MM:SS:FF (75 frames per second for Red Book CD)
    fn seconds_to_cue_time(seconds: f64) -> String {
        let total_frames = (seconds * 75.0).round() as u64;
        let ff = total_frames % 75;
        let total_secs = total_frames / 75;
        let ss = total_secs % 60;
        let mm = total_secs / 60;
        format!("{:02}:{:02}:{:02}", mm, ss, ff)
    }

    /// Sample rate the album is sequenced at: the first active track's rate (at least 44.1 kHz)
    pub fn album_sample_rate(&self) -> Option<u32> {
        self.tracks.iter().find(|t| t.is_active).map(|t| t.sample_rate.max(44100))
    }

    /// Decode every active track and sequence them with pregap silence and per-track gain into one
    /// continuous stereo buffer. Tracks at other rates are sinc-resampled to the album rate.
    pub fn build_album_buffer(&self, progress_cb: impl Fn(f32, &str)) -> Result<AudioBuffer, String> {
        let active_tracks: Vec<&MontageTrack> = self.tracks.iter().filter(|t| t.is_active).collect();
        let target_sr = self
            .album_sample_rate()
            .ok_or_else(|| "No active tracks in album montage".to_string())?;

        let mut album_left: Vec<f32> = Vec::new();
        let mut album_right: Vec<f32> = Vec::new();
        let total_count = active_tracks.len();
        let resampler = SincResampler::default();

        for (idx, track) in active_tracks.iter().enumerate() {
            let msg = format!("Sequencing track {}/{}: {}", idx + 1, total_count, track.title);
            progress_cb(idx as f32 / total_count as f32, &msg);

            // Insert pregap silence if not the first track
            if idx > 0 && track.pause_gap_seconds > 0.001 {
                let gap_frames = (track.pause_gap_seconds * target_sr as f64) as usize;
                album_left.resize(album_left.len() + gap_frames, 0.0);
                album_right.resize(album_right.len() + gap_frames, 0.0);
            }

            let mut track_buf = crate::audio::decoder::load_audio_file(&track.path)
                .map_err(|e| format!("Failed to read track '{}': {}", track.path.display(), e))?;
            if track_buf.sample_rate != target_sr {
                track_buf = resampler.resample_buffer(&track_buf, target_sr);
            }

            let gain_mult = 10.0f32.powf(track.gain_offset_db / 20.0);
            let (left, right) = track_buf.to_stereo();
            album_left.extend(left.iter().map(|s| s * gain_mult));
            album_right.extend(right.iter().map(|s| s * gain_mult));
        }

        Ok(AudioBuffer::from_stereo(album_left, album_right, target_sr))
    }

    /// Export the album unprocessed (gain-balanced tracks only) plus a Red Book CUE sheet
    pub fn export_album<P: AsRef<Path>>(
        &self,
        output_wav_path: P,
        bit_depth: ExportBitDepth,
        progress_cb: impl Fn(f32, &str),
    ) -> Result<PathBuf, String> {
        self.export_album_with_source(output_wav_path, bit_depth, None, RenderSource::Bypass, progress_cb)
    }

    /// Export complete continuous album audio through a mastering source, plus a Red Book CUE sheet
    pub fn export_album_with_source<P: AsRef<Path>>(
        &self,
        output_wav_path: P,
        bit_depth: ExportBitDepth,
        target_sample_rate: Option<u32>,
        source: RenderSource,
        progress_cb: impl Fn(f32, &str),
    ) -> Result<PathBuf, String> {
        if self.tracks.iter().all(|t| !t.is_active) {
            return Err("No active tracks in album montage to export".to_string());
        }
        let out_wav = output_wav_path.as_ref();

        let album = self.build_album_buffer(|p, msg| progress_cb(p * 0.5, msg))?;

        // Inject BWF Metadata
        let bwf = crate::audio::bwf::BwfMetadata {
            description: format!("Album: {} by {}", self.album_title, self.album_artist),
            integrated_lufs: self.target_album_lufs,
            ..Default::default()
        };

        let options = RenderOptions {
            bwf_metadata: Some(bwf),
            target_sample_rate,
            ..Default::default()
        };
        render_to_wav(&album, out_wav, bit_depth, source, Some(options), None, |p| {
            progress_cb(0.5 + p * 0.45, "Mastering album audio...")
        })?;

        progress_cb(0.98, "Writing Red Book CUE sheet...");

        let wav_filename = out_wav
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .to_string();
        let cue_content = self.generate_cue_sheet(&wav_filename);
        let cue_path = out_wav.with_extension("cue");
        std::fs::write(&cue_path, cue_content)
            .map_err(|e| format!("Failed to write CUE sheet: {}", e))?;

        progress_cb(1.0, "Album mastering export complete!");
        Ok(cue_path)
    }
}
