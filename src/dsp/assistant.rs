//! Master Assistant: measures the track (loudness, dynamics, tonal balance, stereo image, low-end
//! phase, resonances) and suggests a chain to reach a genre's typical master, or the sound of a
//! reference track when one is given.

use crate::audio::qc::{analyze_buffer, QcTargets};
use crate::audio::AudioBuffer;
use crate::dsp::{BiquadFilter, EqFilterType, FilterType, MasteringSuite, MatchEq, Module, ModuleKind};

/// Analysis bands for tonal balance
pub const BALANCE_BANDS: [(&str, f32, f32); 7] = [
    ("Sub", 20.0, 60.0),
    ("Bass", 60.0, 200.0),
    ("Low mids", 200.0, 600.0),
    ("Mids", 600.0, 2000.0),
    ("Upper mids", 2000.0, 5000.0),
    ("Presence", 5000.0, 10000.0),
    ("Air", 10000.0, 20000.0),
];
const NB: usize = BALANCE_BANDS.len();
/// Balance is expressed relative to the mids band
const MIDS: usize = 3;

/// Typical master for a genre. Tonal balance is per `BALANCE_BANDS` in dB relative to pink
/// noise, normalised to the mids; these are starting points, not rules, which is why the
/// Assistant only corrects half of any difference.
#[derive(Clone, Copy, Debug)]
pub struct GenreProfile {
    pub name: &'static str,
    pub balance_db: [f32; NB],
    /// True peak minus integrated loudness of a finished master
    pub plr_db: f32,
    pub width: f32,
    /// Mono-maker frequency (Hz); 20 effectively leaves the low end alone
    pub mono_below_hz: f32,
    /// Harmonic exciter mix (0 = leave it off)
    pub exciter_mix: f32,
}

